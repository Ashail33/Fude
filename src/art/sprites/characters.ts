type Kind = 'cat' | 'dog' | 'fox'

function put(rows: string[], x: number, y: number, m: string[]) {
  const out = rows.map((r) => r.split(''))
  m.forEach((r, j) => [...r].forEach((ch, i) => ch !== ' ' && out[y + j] && (out[y + j][x + i] = ch)))
  return out.map((r) => r.join(''))
}

