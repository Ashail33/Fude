/**
 * Walking characters, 16×16, authored as palette maps (see raster.LEGEND).
 * Each has `down`, `up` and `side` (facing right; left is mirrored). The
 * second walk frame is derived (legs swapped) unless given explicitly.
 * Digits are per-character colour slots. The ink outline is added
 * automatically around the silhouette.
 *
 * Human slot convention: 1 cloth, 2 cloth shade, 3 trim, 4 cloth light,
 * 5 hair, 6 hair shade, 7 legs, 8 shoes.
 */
import type { Slots } from '../raster'

export interface CharDef {
  down: string[]
  up: string[]
  side: string[]
  /** Explicit second frames (otherwise derived). */
  down1?: string[]
  up1?: string[]
  side1?: string[]
  slots?: Slots
  /** Leg rows mirrored for the 2nd down/up frame, and the column span. */
  legRows?: [number, number]
  span?: [number, number]
  /** Column span used to gather the legs for the side "passing" frame. */
  sideSpan?: [number, number]
  /** Floating sprite: frame 1 bobs up a pixel instead of walking. */
  float?: boolean
  /** Characters of flat colours to auto-shade (top-left light). */
  shade?: string
}

