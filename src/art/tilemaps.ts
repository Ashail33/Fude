const BAMBOO = (a: number) => {
  const leaf = a ? ['....g', '...gg', '..gg.'] : ['.g...', 'gg...', '.gg..']
  const base = [
    '..Rr.....Rr..Rr.',
    '..Rr.....Rr..Rr.',
    '..GG.....Rr..Rr.',
    '..Rr.....GG..Rr.',
    '..Rr.....Rr..Rr.',
    '..Rr.....Rr..GG.',
    '..Rr.....Rr..Rr.',
    '..Rr.....Rr..Rr.',
    '..Rr.....Rr..Rr.',
    '..GG.....Rr..Rr.',
    '..Rr.....GG..Rr.',
    '..Rr.....Rr..Rr.',
    '..Rr.....Rr..GG.',
    '..Rr.....Rr..Rr.',
    '..Rr.....Rr..Rr.',
    '..Rr.....Rr..Rr.',
  ]
  const rows = base.map((r) => r.split(''))
  const put = (x: number, y: number, m: string[]) =>
    m.forEach((r, j) => [...r].forEach((ch, i) => ch !== '.' && rows[y + j]?.[x + i] !== undefined && (rows[y + j][x + i] = ch)))
  put(3, 3, leaf)
  put(4, 10, leaf)
  put(10, 6, leaf.map((r) => [...r].reverse().join('')))
  return rows.map((r) => r.join(''))
}

