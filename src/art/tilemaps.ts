/**
 * Palette maps for prop tiles (16×16). Flat colours are auto-shaded from
 * the top-left (`shade` lists which colours), then outlined in ink and
 * dropped onto their ground tile with a soft cast shadow.
 */
export interface PropDef {
  rows?: string[]
  /** Animated props: one map per frame. */
  frames?: string[][]
  shade?: string
  /** Cast shadow ellipse [cx, cy, rx, ry] on the ground beneath. */
  shadow?: [number, number, number, number]
}

const LANTERN_BODY = (light: string, glow: string) => [
  '................',
  '......ss........',
  '....ssssss......',
  '..ssssssssss....',
  '.SSSSSSSSSSSS...',
  '...ssssssss.....',
  `...s${glow}${light}${light}${glow}s.....`.slice(0, 16).padEnd(16, '.'),
  `...s${light}${light}${light}${light}s.....`.slice(0, 16).padEnd(16, '.'),
  '...ssssssss.....',
  '....SSSSSS......',
  '.....ssss.......',
  '.....ssss.......',
  '.....ssss.......',
  '...ssssssss.....',
  '...SSSSSSSS.....',
  '................',
]

function shiftRight(rows: string[], n: number) {
  return rows.map((r) => ('.'.repeat(n) + r).slice(0, 16))
}

const LANTERN = (light: string, glow: string) => {
  const r = LANTERN_BODY(light, glow)
  // centre it (body is 12 wide starting at col 1)
  return shiftRight(r, 1).map((row, i) => (i === 6 || i === 7 ? row : row))
}

